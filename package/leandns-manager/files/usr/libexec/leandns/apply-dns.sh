#!/bin/sh
# Apply LeanDNS dnsmasq settings with backup/rollback.
# Safe: no arbitrary shell from network; only controlled UCI/files.

set -eu

BACKUP_DIR=/var/lib/leandns/backup
HOSTS_FILE=/etc/leandns/hosts
DNSMASQ_HOSTS=/tmp/leandns.hosts
DNSMASQ_CONF_D=/tmp/dnsmasq.d
CUSTOM_CONF="$DNSMASQ_CONF_D/leandns.conf"
VALIDATE=/usr/bin/leandns-validate

mkdir -p "$BACKUP_DIR" "$DNSMASQ_CONF_D" /var/lib/leandns

log() {
	logger -t leandns "$*"
}

backup_state() {
	mkdir -p "$BACKUP_DIR"
	cp -a /etc/config/dhcp "$BACKUP_DIR/dhcp" 2>/dev/null || true
	cp -a /etc/config/leandns "$BACKUP_DIR/leandns" 2>/dev/null || true
	cp -a "$HOSTS_FILE" "$BACKUP_DIR/hosts" 2>/dev/null || true
	[ -f "$CUSTOM_CONF" ] && cp -a "$CUSTOM_CONF" "$BACKUP_DIR/leandns.conf" || true
}

restore_state() {
	log "rolling back DNS configuration"
	[ -f "$BACKUP_DIR/dhcp" ] && cp -a "$BACKUP_DIR/dhcp" /etc/config/dhcp
	[ -f "$BACKUP_DIR/leandns" ] && cp -a "$BACKUP_DIR/leandns" /etc/config/leandns
	[ -f "$BACKUP_DIR/hosts" ] && cp -a "$BACKUP_DIR/hosts" "$HOSTS_FILE"
	[ -f "$BACKUP_DIR/leandns.conf" ] && cp -a "$BACKUP_DIR/leandns.conf" "$CUSTOM_CONF"
	uci commit dhcp 2>/dev/null || true
	build_hosts
	/etc/init.d/dnsmasq restart >/dev/null 2>&1 || true
}

build_hosts() {
	: > "$DNSMASQ_HOSTS"
	[ -f "$HOSTS_FILE" ] || return 0
	while IFS= read -r line || [ -n "$line" ]; do
		case "$line" in
			''|\#*) continue ;;
		esac
		# shellcheck disable=SC2086
		set -- $line
		host="${1:-}"
		ip="${2:-}"
		[ -n "$host" ] && [ -n "$ip" ] || continue
		"$VALIDATE" hostrecord "$host" "$ip" || {
			log "skip invalid host record: $line"
			continue
		}
		# dnsmasq hostsfile format: IP hostname
		printf '%s %s\n' "$ip" "$host" >> "$DNSMASQ_HOSTS"
	done < "$HOSTS_FILE"
}

apply_uci() {
	cachesize="$(uci -q get leandns.main.cachesize)"
	domain="$(uci -q get leandns.main.internal_domain)"
	cachesize="${cachesize:-1000}"
	domain="${domain:-home.arpa}"

	"$VALIDATE" cachesize "$cachesize" || {
		log "invalid cachesize $cachesize"
		return 1
	}
	"$VALIDATE" domain "$domain" || {
		log "invalid domain $domain"
		return 1
	}

	uci -q set dhcp.@dnsmasq[0].cachesize="$cachesize"
	uci -q set dhcp.@dnsmasq[0].domain="$domain"
	uci -q set dhcp.@dnsmasq[0].local="/${domain}/"
	uci -q set dhcp.@dnsmasq[0].localservice='1'
	uci -q set dhcp.@dnsmasq[0].addn_hosts="$DNSMASQ_HOSTS"

	# upstream servers from /etc/leandns/upstream.list (preferred) or UCI
	if ! /usr/libexec/leandns/upstream-list.sh apply-dnsmasq; then
		log "invalid upstream list"
		return 1
	fi

	# IPv6 DNS toggle — when disabled, avoid advertising AAAA from local if configured elsewhere
	ipv6="$(uci -q get leandns.main.ipv6_dns)"
	if [ "$ipv6" = "0" ]; then
		uci -q set dhcp.@dnsmasq[0].filter_aaaa='1'
	else
		uci -q delete dhcp.@dnsmasq[0].filter_aaaa 2>/dev/null || true
	fi

	uci commit dhcp
}

write_custom_conf() {
	mkdir -p "$DNSMASQ_CONF_D"
	cat > "$CUSTOM_CONF" <<EOF
# Generated by LeanDNS — do not edit
# local-service / bind handled via UCI
EOF
}

restart_dnsmasq() {
	/etc/init.d/dnsmasq restart
}

do_apply() {
	backup_state
	if [ -n "${1:-}" ]; then
		if ! awk '{h[$1]=$0} END {for (k in h) print h[k]}' "$1" | sort > "$HOSTS_FILE"; then
			restore_state
			return 1
		fi
	fi
	build_hosts
	if ! apply_uci; then
		restore_state
		return 1
	fi
	write_custom_conf
	if ! restart_dnsmasq; then
		log "dnsmasq restart failed — restoring"
		restore_state
		return 1
	fi
	log "DNS configuration applied"
	return 0
}

case "${1:-}" in
	--boot|--apply|"")
		do_apply
		;;
	--hosts)
		[ "$#" = 2 ] && [ -f "$2" ] || exit 2
		do_apply "$2"
		;;
	--rollback)
		restore_state
		;;
	*)
		echo "usage: $0 [--boot|--apply|--hosts FILE|--rollback]" >&2
		exit 2
		;;
esac
