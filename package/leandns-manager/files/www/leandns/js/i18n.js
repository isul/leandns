  function detectLocale() {
    const list = (typeof navigator !== 'undefined' && (navigator.languages || [navigator.language])) || ['en'];
    for (let i = 0; i < list.length; i++) {
      const lang = String(list[i] || '').toLowerCase();
      if (lang === 'ko' || lang.indexOf('ko-') === 0) return 'ko';
    }
    return 'en';
  }

  const locale = detectLocale();
  const numberLocale = locale === 'ko' ? 'ko-KR' : 'en-US';

  function t(key, vars) {
    const dict = STRINGS[locale] || STRINGS.en;
    let s = (dict && dict[key]) || (STRINGS.en && STRINGS.en[key]) || key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        s = s.split('{' + k + '}').join(String(vars[k]));
      });
    }
    return s;
  }

  function apply() {
    if (typeof document === 'undefined') return;
    document.documentElement.lang = locale;
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
    document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });
  }

  function localizeType(raw) {
    const v = String(raw || '');
    if (v === 'ad' || v === '광고' || v === 'Ad') return t('type.ad');
    if (v === 'track' || v === '추적' || v === 'Tracker') return t('type.track');
    return t('type.block');
  }

  function typeClass(raw) {
    const v = String(raw || '');
    if (v === 'ad' || v === '광고' || v === 'Ad') return 'type-ad';
    if (v === 'track' || v === '추적' || v === 'Tracker') return 'type-track';
    return 'type-block';
  }

  global.LeanI18n = { t, apply, locale, numberLocale, localizeType, typeClass, detectLocale };
